"""Embed the offline installer catalogs; --check is a release consistency check."""
from __future__ import annotations

import argparse
import json
import shlex
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
START = '# BEGIN GENERATED INSTALLER CATALOGS'
END = '# END GENERATED INSTALLER CATALOGS'


def generated():
    languages = json.loads((ROOT / 'locales/languages.json').read_text(encoding='utf-8'))
    lines = [START, '# Generated by localization/generate_installer.py; edit locales/*/installer.json.',
             'LANGUAGE_CODES=(' + ' '.join(shlex.quote(code) for code in languages) + ')',
             'LANGUAGE_NAMES=(' + ' '.join(shlex.quote(item['name']) for item in languages.values()) + ')',
             'declare -A INSTALLER_TEXT', 'load_installer_messages() {', '    case "$INSTALLATION_LANGUAGE" in']
    keys = None
    for code in languages:
        messages = json.loads((ROOT / 'locales' / code / 'installer.json').read_text(encoding='utf-8'))
        if keys is None:
            keys = set(messages)
        if set(messages) != keys or any(not isinstance(value, str) for value in messages.values()):
            raise ValueError('Incomplete installer catalog: ' + code)
        lines.append('        ' + shlex.quote(code) + ') INSTALLER_TEXT=(')
        lines.extend('            [' + shlex.quote(key) + ']=' + shlex.quote(value) for key, value in messages.items())
        lines.append('        ) ;;')
    lines.extend(['        *) return 2 ;;', '    esac', '}', 'load_installer_messages', END])
    return '\n'.join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    path = ROOT / 'install.sh'
    source = path.read_text(encoding='utf-8')
    start, end = source.index(START), source.index(END) + len(END)
    updated = source[:start] + generated() + source[end:]
    if args.check:
        if source != updated:
            raise SystemExit('Installer catalogs need regeneration')
    else:
        path.write_text(updated, encoding='utf-8', newline='\n')


if __name__ == '__main__':
    main()
