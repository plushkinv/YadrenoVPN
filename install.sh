# ПУНКТ 3: АВАРИЙНАЯ ЖЁСТКАЯ ПЕРЕЗАПИСЬ (git fetch + reset)
# ============================================================
do_hard_reset() {
    print_header "$(installer_text do_hard_reset.1)"

    if [ ! -d "$INSTALL_DIR/.git" ]; then
        print_err "$(installer_text do_soft_update.2 "$INSTALL_DIR")"
        return 1
    fi

    echo -e "$(installer_text do_hard_reset.2 "${RED}" "${NC}")"
    echo -e "$(installer_text do_hard_reset.3 "${YELLOW}" "${NC}")"
    if [ "$AUTO_MODE" = "1" ] || [ "$REINSTALL_EXISTING" = "1" ]; then
        confirm="y"
    else
        read -p "$(installer_text do_hard_reset.4)" confirm || return 130
    fi
    if [[ ! "$confirm" =~ ^[YyДд]$ ]]; then
        echo "$(installer_text do_hard_reset.5)"
        return 0
    fi

    cd "$INSTALL_DIR"
    if ! acquire_update_operation_lock; then
        return 1
    fi

    if ! git fetch -q origin; then
        print_err "$(installer_text do_hard_reset.6)"
        release_update_operation_lock
        return 1
    fi

    local target
    if ! target=$(resolve_install_target "${TARGET_COMMIT:-}"); then
        release_update_operation_lock
        return 1
    fi
    print_ok "$(installer_text do_hard_reset.7 "${target:0:8}")"

    local mode="installer_reset"
    if [ "$REINSTALL_EXISTING" = "1" ]; then
        mode="installer_reinstall"
    fi
    local service_was_active=0
    if systemctl is-active --quiet yadreno-vpn; then
        service_was_active=1
    fi
    if ! systemctl stop yadreno-vpn; then
        print_err "$(installer_text do_hard_reset.8)"
        release_update_operation_lock
        return 1
    fi

    UPDATE_SNAPSHOT_ID=""
    if ! prepare_update_snapshot "$mode" "$target"; then
        if [ "$service_was_active" = "1" ]; then
            systemctl start yadreno-vpn || true
        fi
        release_update_operation_lock
        return 1
    fi

    if ! write_git_tree reset --hard "$target" -q; then
        print_err "$(installer_text do_hard_reset.9)"
        systemctl start yadreno-vpn || true
        release_update_operation_lock
        return 1
    fi

    if ! mark_update_snapshot_applied; then
        print_err "$(installer_text do_hard_reset.10)"
        release_update_operation_lock
        return 1
    fi
    if ! git clean -fd -q \
        -e backup/ \
        -e config.py \
        -e custom_extensions/ \
        -e user_files/ \
        -e custom_web/ \
        -e web_runtime/ \
        -e database/vpn_bot.db \
        -e database/vpn_bot.db-wal \
        -e database/vpn_bot.db-shm \
        -e logs/ \
        -e venv/; then
        print_err "$(installer_text do_hard_reset.11)"
        release_update_operation_lock
        return 1
    fi
    print_ok "$(installer_text do_hard_reset.12 "${target:0:8}")"

    if ! "$VENV_DIR/bin/python" -m pip install --upgrade -r requirements.txt -q; then
        print_err "$(installer_text do_hard_reset.13)"
        release_update_operation_lock
        return 1
    fi
    print_ok "$(installer_text do_hard_reset.14)"

    if ! setup_systemd; then
        print_err "$(installer_text do_hard_reset.15)"
        release_update_operation_lock
        return 1
    fi

    if ! systemctl start yadreno-vpn; then
        print_err "$(installer_text do_hard_reset.16)"
        release_update_operation_lock
        return 1
    fi
    sleep 2
    if systemctl is-active --quiet yadreno-vpn; then
        print_ok "$(installer_text do_hard_reset.17)"
        release_update_operation_lock
        return 0
    fi

    print_err "$(installer_text do_hard_reset.18)"
    echo "  bash install.sh rollback SNAPSHOT_ID"
    release_update_operation_lock
    return 1
}

