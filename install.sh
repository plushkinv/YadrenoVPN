# ПУНКТ 2: ШТАТНОЕ МЯГКОЕ ОБНОВЛЕНИЕ (fast-forward)
# ============================================================
do_soft_update() {
    print_header "$(installer_text do_soft_update.1)"

    if [ ! -d "$INSTALL_DIR/.git" ]; then
        print_err "$(installer_text do_soft_update.2 "$INSTALL_DIR")"
        return 1
    fi

    cd "$INSTALL_DIR"
    # The downloaded installer may run against an older installed updater.
    # Resolve the marked stage here as well so that version cannot skip the
    # first blocking commit before the target code takes over this policy.
    local fetch_error
    if ! fetch_error=$(git fetch -q origin 2>&1); then
        printf '%s\n' "$fetch_error"
        if [[ "$fetch_error" == *"detected dubious ownership"* ]] && \
            [ -f "$INSTALL_DIR/web_tools/permissions.py" ] && [ -x "$VENV_DIR/bin/python" ]; then
            "$VENV_DIR/bin/python" -B - <<'PY'
from pathlib import Path
from bot.services.update_rollback import UpdateRollbackError, _web_release_command
try:
    _web_release_command(Path.cwd(), 'check-paths', '--git-owner')
except UpdateRollbackError as error:
    print(str(error))
PY
        fi
        print_err "$(installer_text do_soft_update.3)"
        return 1
    fi
    local resolved_target
    if ! resolved_target=$(resolve_install_target "${TARGET_COMMIT:-}"); then
        return 1
    fi
    local requested_target="$resolved_target"
    print_ok "$(installer_text do_soft_update.4 "${resolved_target:0:8}")"
    recover_legacy_tracked_service_file || return 1
    local blocking_commit=""
    local commit_subject=""
    while IFS='|' read -r commit_hash commit_subject; do
        if [[ "$commit_subject" == \!* ]]; then
            blocking_commit="$commit_hash"
            break
        fi
    done < <(git log "HEAD..$resolved_target" --format='%H|%s' --reverse)

    if [ -n "$blocking_commit" ]; then
        requested_target="$blocking_commit"
        print_warn "$(installer_text do_soft_update.5 "${blocking_commit:0:8}")"
    fi
    local update_args=(
        update
        --project-root "$INSTALL_DIR"
        --mode "installer_update"
        --target "$requested_target"
        --strategy "pull"
        --actor "installer"
        --service-name "yadreno-vpn"
    )
    if [ -n "$blocking_commit" ]; then
        update_args+=(--block-updates)
    fi

    local output
    if ! output=$(
        "$VENV_DIR/bin/python" -m bot.services.update_rollback "${update_args[@]}" 2>&1
    ); then
        print_err "$(installer_text do_soft_update.6)"
        echo "$output"
        return 1
    fi
    print_ok "$output"
    setup_systemd
}

