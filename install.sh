installer_text() {
    local key="$1" template marker index result=""
    shift
    local parameters=("$@")
    template="${INSTALLER_TEXT[$key]}"
    while [[ "$template" =~ \{p([0-9]+)\} ]]; do
        marker="${BASH_REMATCH[0]}"
        index="${BASH_REMATCH[1]}"
        result+="${template%%"$marker"*}${parameters[$index]}"
        template="${template#*"$marker"}"
    done
    printf '%s' "$result$template"
}

valid_language() {
    local code
    for code in "${LANGUAGE_CODES[@]}"; do
        [ "$code" != "$1" ] || return 0
    done
    return 1
}

parse_install_arguments() {
    POSITIONAL=()
    while [ "$#" -gt 0 ]; do
        case "$1" in
            --language|--language=*)
                if [ "$LANGUAGE_EXPLICIT" = 1 ]; then
                    print_err "$(installer_text parse_install_arguments.1)"
                    return 2
                fi
                LANGUAGE_EXPLICIT=1
                local code
                if [ "$1" = --language ]; then
                    if [ "$#" -lt 2 ]; then print_err "$(installer_text parse_install_arguments.2)"; return 2; fi
                    code="$2"; shift
                else
                    code="${1#--language=}"
                fi
                if ! valid_language "$code"; then
                    print_err "$(installer_text parse_install_arguments.3 "$code")"
                    return 2
                fi
                INSTALLATION_LANGUAGE="$code"
                load_installer_messages
                ;;
            *) POSITIONAL+=("$1") ;;
        esac
        shift
    done
    local action="${POSITIONAL[0]:-}"
    case "$action" in
        install)
            if [ "${#POSITIONAL[@]}" -ne 3 ]; then
                print_err "$(installer_text parse_install_arguments.4)"
                return 2
            fi
            if [[ ! "${POSITIONAL[1]}" =~ ^[0-9]+:[A-Za-z0-9_-]{20,128}$ ]] || [[ ! "${POSITIONAL[2]}" =~ ^[1-9][0-9]*$ ]]; then
                print_err "$(installer_text parse_install_arguments.5)"
                return 2
            fi
            ;;
        update|reset)
            if [ "${#POSITIONAL[@]}" -gt 2 ] || [[ "${POSITIONAL[1]:-}" == -* ]]; then
                print_err "$(installer_text parse_install_arguments.6)"
                return 2
            fi
            ;;
        rollback)
            if [ "${#POSITIONAL[@]}" -ne 2 ] || [[ ! "${POSITIONAL[1]}" =~ ^[0-9]{8}T[0-9]{12}Z_[0-9a-fA-F]{8}$ ]]; then
                print_err "$(installer_text parse_install_arguments.7)"
                return 2
            fi
            ;;
        web-setup) ;;
        '')
            if [ ! -t 0 ]; then
                print_err "$(installer_text parse_install_arguments.8)"
                return 2
            fi
            ;;
        *) print_err "$(installer_text parse_install_arguments.9 "$action")"; return 2 ;;
    esac
}

load_existing_language() {
    [ -f "$DB_PATH" ] || return 0
    local python_bin="$VENV_DIR/bin/python" saved
    if [ ! -x "$python_bin" ]; then python_bin=$(command -v python3 || true); fi
    if [ -z "$python_bin" ]; then
        print_err "$(installer_text load_existing_language.1)"
        return 1
    fi
    if ! saved=$("$python_bin" -I - "$DB_PATH" <<'PY'
import sqlite3, sys
from contextlib import closing
from pathlib import Path
with closing(sqlite3.connect(Path(sys.argv[1]).resolve().as_uri() + '?mode=ro', uri=True)) as conn:
    has_settings = conn.execute("SELECT 1 FROM sqlite_master WHERE type='table' AND name='settings'").fetchone()
    row = conn.execute("SELECT value FROM settings WHERE key='installation_language'").fetchone() if has_settings else None
    print(row[0] if row else 'ru')
PY
    ); then
        print_err "$(installer_text load_existing_language.2)"
        return 1
    fi
    if ! valid_language "$saved"; then
        print_err "$(installer_text load_existing_language.3 "$saved")"
        return 1
    fi
    if [ "$LANGUAGE_EXPLICIT" = 1 ] && [ "$saved" != "$INSTALLATION_LANGUAGE" ]; then
        print_err "$(installer_text load_existing_language.4 "$saved")"
        return 2
    fi
    INSTALLATION_LANGUAGE="$saved"
    load_installer_messages
}

select_installation_language() {
    [ "$LANGUAGE_EXPLICIT" != 1 ] && [ ! -f "$DB_PATH" ] && [ "${AUTO_MODE:-0}" != 1 ] || return 0
    print_header "$(installer_text select_installation_language.1)"
    local selected=0 key sequence number first=1 index
    if [ -t 0 ] && [ -t 1 ] && [ "${TERM:-dumb}" != dumb ]; then
        printf '\033[?25l'
        trap 'printf "\033[?25h"; exit 130' INT TERM
        while true; do
            if [ "$first" != 1 ]; then printf '\033[%dA' "${#LANGUAGE_CODES[@]}"; fi
            first=0
            for index in "${!LANGUAGE_CODES[@]}"; do
                if [ "$index" = "$selected" ]; then printf '\r\033[K > %s\n' "${LANGUAGE_NAMES[$index]}";
                else printf '\r\033[K   %s\n' "${LANGUAGE_NAMES[$index]}"; fi
            done
            if ! IFS= read -rsn1 key; then printf '\033[?25h'; trap - INT TERM; return 130; fi
            case "$key" in
                '') break ;;
                $'\033')
                    # This deadline only disambiguates Escape from an ANSI key sequence.
                    # The selection itself never times out or accepts automatically.
                    if ! IFS= read -rsn2 -t 0.15 sequence; then printf '\033[?25h'; trap - INT TERM; return 130; fi
                    case "$sequence" in
                        '[A'|'OA') selected=$(( (selected + ${#LANGUAGE_CODES[@]} - 1) % ${#LANGUAGE_CODES[@]} )) ;;
                        '[B'|'OB') selected=$(( (selected + 1) % ${#LANGUAGE_CODES[@]} )) ;;
                    esac ;;
                q|Q) printf '\033[?25h'; trap - INT TERM; return 130 ;;
            esac
        done
        printf '\033[?25h'
        trap - INT TERM
    else
        for index in "${!LANGUAGE_CODES[@]}"; do printf '  %d) %s\n' "$((index + 1))" "${LANGUAGE_NAMES[$index]}"; done
        while true; do
            if ! read -r -p "$(installer_text select_installation_language.2)" number; then return 130; fi
            [ "$number" != q ] && [ "$number" != Q ] || return 130
            number="${number:-1}"
            if [[ "$number" =~ ^[0-9]{1,2}$ ]] && [ "$((10#$number))" -ge 1 ] && [ "$((10#$number))" -le "${#LANGUAGE_CODES[@]}" ]; then
                selected=$((10#$number - 1)); break
            fi
            print_err "$(installer_text select_installation_language.3)"
        done
    fi
    INSTALLATION_LANGUAGE="${LANGUAGE_CODES[$selected]}"
    load_installer_messages
}

