# ПУНКТ 4: ОТКАТ ПО PRE-UPDATE BACKUP
# ============================================================
do_rollback() {
    print_header "$(installer_text do_rollback.1)"

    if [ ! -d "$INSTALL_DIR/.git" ]; then
        print_err "$(installer_text do_soft_update.2 "$INSTALL_DIR")"
        return 1
    fi
    cd "$INSTALL_DIR"
    local python_bin="$VENV_DIR/bin/python"
    if [ ! -x "$python_bin" ]; then
        python_bin=$(command -v python3 || true)
    fi
    if [ -z "$python_bin" ] || [ ! -x "$python_bin" ]; then
        print_err "$(installer_text do_rollback.2)"
        return 1
    fi

    local runner=""
    local candidate
    for candidate in "$INSTALL_DIR"/backup/pre_update/*/rollback_runner.py; do
        if [ ! -f "$candidate" ]; then
            continue
        fi
        if [ -z "$runner" ] || [ "$candidate" -nt "$runner" ]; then
            runner="$candidate"
        fi
    done
    if [ -z "$runner" ]; then
        print_err "$(installer_text do_rollback.3)"
        return 1
    fi

    if [ "${AUTO_MODE:-0}" = 1 ]; then
        "$python_bin" "$runner" rollback --snapshot-id "$ROLLBACK_SNAPSHOT" \
            --project-root "$INSTALL_DIR" --service-name "yadreno-vpn" < /dev/null
        return $?
    fi
    "$python_bin" "$runner" interactive \
        --project-root "$INSTALL_DIR" \
        --service-name "yadreno-vpn"
}

